/**
 * @file    _start.s
 * @brief   用户态程序启动代码（AArch64）
 * @version 1.0
 *
 * 用户态程序的入口点：
 * - 设置栈指针
 * - 调用 C 运行时初始化
 * - 调用 main() 函数
 * - 处理退出代码
 *
 * @note MISRA-C:2012 合规（汇编层面）
 * @note AISafeOS64 用户态服务使用
 */

    .global _start
    .global _exit

    .text
    .align 4

/* ========================================================================
 * _start - 用户态程序入口
 * ======================================================================== */

/**
 * @brief 用户态程序入口点
 *
 * 标准约定：
 * - 第一个参数通过 x0 传递
 * - 剩余参数通过 x1-x5 传递
 * - 返回值通过 x0 返回（退出代码）
 */
_start:
    /* ====================================================================
     * 保存栈指针（初始栈地址）
     * ==================================================================== */
    mov     sp, x0          /* 栈指针 = 第一个参数 */

    /* ====================================================================
     * 调用 C 运行时初始化
     * ==================================================================== */
    bl      __libc_init    /* 调用 libc 初始化 */

    /* ====================================================================
     * 准备 main() 函数调用
     * ==================================================================== */
    mov     x0, #0          /* argc = 0 */
    mov     x1, xzr         /* argv = NULL */

    /* ====================================================================
     * 调用 main() 函数
     * ==================================================================== */
    bl      main            /* 调用 main 函数 */
    mov     x0, x0          /* 退出代码 = main 的返回值 */

    /* ====================================================================
     * 调用 _exit() 退出程序
     * ==================================================================== */
    bl      _exit           /* 退出程序 */

    /* ====================================================================
     * 程序退出（不应到达这里）
     * ==================================================================== */
1:  b       1b              /* 死循环 */

/* ========================================================================
 * _exit - 退出程序
 * ======================================================================== */

/**
 * @brief 退出程序并返回退出代码
 *
 * @param exit_code 退出代码
 */
_exit:
    /* 调用内核系统调用来退出 */
    mov     x8, #0x0002     /* SYS_THREAD_EXIT */
    svc     #0              /* 调用内核系统调用 */

    /* 不应到达这里 */
1:  b       1b              /* 死循环 */
